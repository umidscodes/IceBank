// node scripts/list-testids.mjs > docs/LOCATORS.md  — regenerates the data-testid contract from the source.
import fs from "node:fs";
import path from "node:path";
const roots = ["src/app", "src/ui"];
const files = [];
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) { if (!p.includes(`${path.sep}api`)) walk(p); } else if (/\.tsx?$/.test(e.name)) files.push(p); } };
roots.forEach(walk);
const pageOf = (f) => {
  const rel = f.split(path.sep).join("/");
  if (rel.startsWith("src/app/")) return rel.replace("src/app", "").replace(/\/\([^)]+\)/g, "").replace(/\/page\.tsx$/, "").replace(/\/layout\.tsx$/, " (layout)") || "/";
  return `shared: ${rel.replace("src/ui/", "")}`;
};
const out = ["# Locator list (data-testid)", "", "Generated by `node scripts/list-testids.mjs`. `${...}` parts are filled at runtime (usually an id, an account type or a yyyy-mm month).", "",
  "Classic view (Profile > Classic view) deliberately has **no** test ids on the dashboard, account transactions and payees pages.", ""];
const byPage = new Map();
for (const f of files.sort()) {
  const src = fs.readFileSync(f, "utf8");
  const ids = new Set();
  for (const m of src.matchAll(/(?:data-testid|testId)=\{?(["'`])([^"'`]+)\1/g)) ids.add(m[2]);
  for (const m of src.matchAll(/testId: ["'`]([^"'`]+)["'`]/g)) ids.add(m[1]);
  if (ids.size) byPage.set(pageOf(f), [...(byPage.get(pageOf(f)) ?? []), ...ids]);
}
const keys = [...byPage.keys()].sort((a, b) => (a.startsWith("shared") ? 1 : 0) - (b.startsWith("shared") ? 1 : 0) || a.localeCompare(b));
for (const k of keys) { out.push(`## ${k}`, "", ...[...new Set(byPage.get(k))].sort().map((i) => `- \`${i}\``), ""); }
process.stdout.write(out.join("\n"));
